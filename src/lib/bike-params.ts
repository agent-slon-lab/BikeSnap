/**
 * Категория параметра для цветовой кодировки
 * - input: пользователь вводит вручную
 * - calculated: рассчитывается автоматически по формулам
 * - reference: справочный (не используется в расчётах, только для понимания)
 */
export type ParamCategory = "input" | "calculated" | "reference";

export interface BikeParamInfo {
  /** Международная аббревиатура (ETT, Reach, Stack и т.д.) */
  abbr: string;
  /** Полное название на английском */
  fullNameEn: string;
  /** Полное название на русском */
  fullNameRu: string;
  /** Краткое пояснение для новичка (1-2 предложения) */
  shortDescription: string;
  /** Развернутое пояснение с физикой и зачем это нужно */
  detailedDescription: string;
  /** Как измерить рулеткой */
  howToMeasure: string;
  /** Единица измерения */
  unit: "mm" | "°" | "ratio";
  /** Категория (ввод/расчёт/справка) */
  category: ParamCategory;
  /** Диапазон нормы (для справки) */
  typicalRange?: [number, number];
  /** Зависимости для расчёта (если calculated) */
  dependsOn?: string[];
  /** Какую роль играет в посадке */
  bikeFitRole: string;
}

