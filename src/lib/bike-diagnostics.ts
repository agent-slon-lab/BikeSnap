/**
 * Диагностика посадки по жалобам райдера и углам суставов.
 *
 * Связывает жалобы (боль в колене, спине, шее) с измеренными углами
 * и выдаёт конкретные рекомендации в миллиметрах.
 */

export interface DiagnosticResult {
  title: string;
  recommendations: string[];
}

/**
 * Анализ жалоб с учётом углов колена и тазобедренного сустава.
 *
 * @param complaints Массив идентификаторов жалоб
 * @param kneeAngle Угол колена в НМТ (6 часов), градусов (140-155 — норма)
 * @param hipAngle Угол тазобедренного сустава (50-65 — норма для комфорта)
 * @param backAngle Угол наклона спины от горизонтали (35-65 — норма)
 * @returns Массив диагностических результатов с рекомендациями
 */
export function analyzeComplaints(
  complaints: string[],
  kneeAngle: number,
  hipAngle: number,
  backAngle?: number,
): DiagnosticResult[] {
  const results: DiagnosticResult[] = [];

  // Боль в передней части колена
  if (complaints.includes('knee_front_pain')) {
    if (kneeAngle < 140) {
      results.push({
        title: 'Боль в передней части колена',
        recommendations: [
          `Колено слишком сильно согнуто (${kneeAngle}° при норме 140-148°).`,
          `Поднимите подседельный штырь на ${Math.round((145 - kneeAngle) * 2.5)} мм (1° ≈ 2.5 мм).`,
          'Сдвиньте седло назад на 3-5 мм для снижения нагрузки на коленную чашечку.',
        ]
      });
    } else if (kneeAngle > 155) {
      results.push({
        title: 'Боль в передней части колена',
        recommendations: [
          `Колено слишком прямое (${kneeAngle}° при норме 140-148°).`,
          `Опустите подседельный штырь на ${Math.round((kneeAngle - 148) * 2.5)} мм.`,
          'Возможно, седло слишком высоко — происходит раскачка таза.',
        ]
      });
    } else {
      results.push({
        title: 'Боль в передней части колена (угол в норме)',
        recommendations: [
          'Угол колена в норме — проверьте положение шипов на велотуфлях.',
          'Ось педали должна проходить под подушечкой стопы (KOPS).',
          'Проверьте длину шатуна — возможно, он слишком длинный.',
        ]
      });
    }
  }

  // Боль в задней части колена
  if (complaints.includes('knee_back_pain')) {
    results.push({
      title: 'Боль в задней части колена',
      recommendations: [
        'Седло может быть слишком высоко — попробуйте опустить на 3-5 мм.',
        'Проверьте, не слишком ли далеко седло отодвинуто назад (setback).',
      ]
    });
  }

  // Боль в пояснице
  if (complaints.includes('lower_back_pain')) {
    if (backAngle != null && backAngle < 35) {
      results.push({
        title: 'Перегрузка поясницы (слишком низко)',
        recommendations: [
          `Спина слишком горизонтальна (${backAngle}° при норме 50-65°).`,
          'Добавьте проставки под вынос (поднять руль на 5-10 мм).',
          'Или замените вынос на более короткий (на 10 мм).',
        ]
      });
    } else if (hipAngle < 45) {
      results.push({
        title: 'Перегрузка поясницы',
        recommendations: [
          'Угол в тазобедренном суставе слишком острый — поднимите руль.',
          'Установите более короткие шатуны (например, 165 мм вместо 172.5 мм).',
        ]
      });
    } else {
      results.push({
        title: 'Боль в пояснице',
        recommendations: [
          'Проверьте гибкость поясницы — возможно, нужен более высокий Stack.',
          'Попробуйте вынос с большим углом (+10° вместо +6°).',
        ]
      });
    }
  }

  // Боль в шее
  if (complaints.includes('neck_pain')) {
    results.push({
      title: 'Боль в шее',
      recommendations: [
        'Слишком низкая посадка — поднимите руль (добавьте проставки).',
        'Проверьте угол спины — если < 40°, нужно поднять Stack.',
      ]
    });
  }

  // Онемение рук
  if (complaints.includes('hand_numbness')) {
    results.push({
      title: 'Онемение рук',
      recommendations: [
        'Слишком много веса на руках — поднимите руль или сдвиньте седло вперёд.',
        'Проверьте угол локтя — руки должны быть слегка согнуты (145-165°).',
        'Возможно, вынос слишком длинный — попробуйте на 10 мм короче.',
      ]
    });
  }

  // Онемение стопы
  if (complaints.includes('foot_numbness')) {
    results.push({
      title: 'Онемение стопы',
      recommendations: [
        'Проверьте положение шипов — сместите их назад на 2-3 мм.',
        'Проверьте жёсткость подошвы велотуфель.',
      ]
    });
  }

  return results;
}
