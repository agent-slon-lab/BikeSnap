/**
 * PHOTO PROVENANCE — защита от подмены фото между велосипедами (v1.14.37)
 * =========================================================================
 * Жалоба: «на шаге 2 был один велик, в шаге 4 другой подсунул — ИИ не
 * увидел» + повтор: «ИИ не видит что я подменил велики» (отчёты v1.14.36).
 *
 * Почему существующей Bike Match Validation мало (отчёты 2026-10-15):
 *  1. Авто-детектор колёс на реальных фото райдера слеп (серая стена,
 *     кирпичный пол, гараж): 0–1 колеса из 2 → ratio = null → сверка
 *     «unknown» (в v1.14.36 это честно показывается, но не ловит подмену).
 *  2. Даже когда детектор работает, у РАЗНЫХ велов пропорция
 *     wheelbase/диаметр может совпадать в пределах 2–5% (реальный кейс:
 *     MTB 1.509 vs гибрид 1.546 — Δ2.4% при пороге 12%).
 *
 * Решение — детерминированный сигнал ПРОИСХОЖДЕНИЯ: каждое загруженное
 * фото получает фингерпринт (djb2 по сжатому dataURL — стабилен между
 * сессиями) и регистрируется за великом, активным в момент загрузки.
 * То же фото под ДРУГИМ велом → конфликт → красная плашка «фото уже
 * использовалось с другим велом». Подмена существующих файлов ловится
 * на 100%, независимо от качества фото и фонов.
 */

export interface PhotoProvenanceEntry {
  /** Велик, под которым фото зарегистрировано (null — черновик без вела) */
  bikeId: string | null;
  /** Имя велика на момент регистрации (для текста плашки) */
  bikeName: string | null;
  view: string;
  at: number;
}

/**
 * djb2-хеш строки → hex. dataURL сжатого фото (~100–300 КБ) хешируется за
 * единицы мс. Стабилен между сессиями: сжатие детерминировано (один и тот же
 * canvas-пайплайн ≤1280px JPEG), тот же исходный файл → тот же dataURL.
 */
export function fingerprintDataUrl(dataUrl: string): string {
  let h = 5381;
  // Шаг 7: полный проход по строке; для скорости читаем чанки через charCodeAt
  for (let i = 0; i < dataUrl.length; i++) {
    h = ((h << 5) + h + dataUrl.charCodeAt(i)) | 0;
  }
  // Второй проход с другой солью — пара хешей вместо одного (коллизии djb2
  // на структурированных JPEG-данных дешёвее подавить парой независимых хешей,
  // чем длинным хешем): h2 = djb2 с начальным 52711 и умножением на 33^2
  let h2 = 52711;
  for (let i = dataUrl.length - 1; i >= 0; i--) {
    h2 = ((h2 << 5) + h2 + dataUrl.charCodeAt(i)) | 0;
  }
  return (
    (h >>> 0).toString(16).padStart(8, "0") +
    (h2 >>> 0).toString(16).padStart(8, "0")
  );
}

/**
 * Конфликт происхождения: это фото уже регистрировалось под ДРУГИМ велом?
 * Возвращает запись прежней регистрации (самую свежую) или null.
 * Один и тот же bikeId (в т.ч. оба null) — конфликта нет.
 */
export function pickProvenanceConflict(
  entries: PhotoProvenanceEntry[] | undefined,
  bikeId: string | null
): PhotoProvenanceEntry | null {
  if (!entries || entries.length === 0) return null;
  for (let i = entries.length - 1; i >= 0; i--) {
    if (entries[i].bikeId !== bikeId) return entries[i];
  }
  return null;
}
